// Derives a centerline + width + color profile for the design ribbon from
// RIBBON_QUADS (src/data/ribbonColors.ts), and writes it to
// src/data/ribbonProfile.ts for use by the animated WebGL ribbon.
//
// Each quad's points are [leftEdge_i, leftEdge_{i+1}, rightEdge_{i+1}, rightEdge_i],
// chained so leftEdge_{i+1} of quad i === leftEdge_i of quad i+1 (and similarly
// for the right edge). Re-run this script if RIBBON_QUADS is regenerated.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const src = fs.readFileSync(path.join(root, "src/data/ribbonColors.ts"), "utf8");
const re = /points: "([^"]+)", color: "(#[0-9a-fA-F]{6})" /g;
const quads = [];
let m;
while ((m = re.exec(src))) {
  const pts = m[1]
    .trim()
    .split(/\s+/)
    .map((p) => p.split(",").map(Number));
  quads.push({ pts, color: m[2] });
}

// The SVG ribbon is rendered inside <g transform="translate(0, -90)">.
// Bake that shift in, and flip Y so it matches Three.js world space
// (camera top=0, bottom=-802 maps SVG y=0 -> screen top).
const SHIFT_Y = -90;
const transform = ([x, y]) => [x, -(y + SHIFT_Y)];

const N = quads.length + 1; // 281 sample points for 280 quads
const left = new Array(N);
const right = new Array(N);

left[0] = right[0] = transform(quads[0].pts[0]);
for (let i = 1; i < quads.length; i++) {
  left[i] = transform(quads[i].pts[0]);
  right[i] = transform(quads[i].pts[3]);
}
left[N - 1] = right[N - 1] = transform(quads[quads.length - 1].pts[1]);

const hexToRgb = (hex) => {
  const v = parseInt(hex.slice(1), 16);
  return [(v >> 16) & 255, (v >> 8) & 255, v & 255];
};

let maxWidth = 0;
const samples = [];
for (let i = 0; i < N; i++) {
  const [lx, ly] = left[i];
  const [rx, ry] = right[i];
  const cx = (lx + rx) / 2;
  const cy = (ly + ry) / 2;
  const dx = rx - lx;
  const dy = ry - ly;
  const width = Math.hypot(dx, dy);
  maxWidth = Math.max(maxWidth, width);

  const color = hexToRgb(quads[Math.min(i, quads.length - 1)].color);

  samples.push({ x: cx, y: cy, dx, dy, width, color });
}

// The artwork's two open path tips (i=0 and i=N-1) are degenerate
// zero-width points. Borrow the normal direction from their nearest
// non-degenerate neighbor, and floor their width to MIN_WIDTH so the
// ribbon never tapers to a point — its width stays continuous end to end.
const MIN_WIDTH = 6;
for (let i = 0; i < N; i++) {
  if (samples[i].width === 0) {
    const neighbor = samples[i === 0 ? 1 : i - 1];
    samples[i].dx = neighbor.dx;
    samples[i].dy = neighbor.dy;
    samples[i].width = MIN_WIDTH;
  }
}

const normalized = samples.map((s) => {
  const len = Math.hypot(s.dx, s.dy) || 1;
  return {
    x: round(s.x),
    y: round(s.y),
    nx: round(s.dx / len),
    ny: round(s.dy / len),
    width: round(s.width),
    color: s.color,
  };
});

function round(n) {
  return Math.round(n * 1000) / 1000;
}

const out = `// Generated by scripts/generate-ribbon-profile.mjs from RIBBON_QUADS.
// Do not edit by hand — re-run the script if RIBBON_QUADS changes.

export interface RibbonSample {
  x: number;
  y: number;
  nx: number;
  ny: number;
  width: number;
  color: [number, number, number];
}

export const RIBBON_MAX_WIDTH = ${round(maxWidth)};

export const RIBBON_SAMPLES: RibbonSample[] = ${JSON.stringify(normalized)
  .replace(/"x"/g, "x")
  .replace(/"y"/g, "y")
  .replace(/"nx"/g, "nx")
  .replace(/"ny"/g, "ny")
  .replace(/"width"/g, "width")
  .replace(/"color"/g, "color")};
`;

fs.writeFileSync(path.join(root, "src/data/ribbonProfile.ts"), out);
console.log(`Wrote ${N} samples (maxWidth=${round(maxWidth)}) to src/data/ribbonProfile.ts`);
